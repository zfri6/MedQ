    //========================================================================
    // Phase accumulator (advances by freq_inc each stb)
    //========================================================================
    reg  [23:0] phase;
    wire [23:0] phase_next;

    assign phase_next = phase + freq_inc;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            phase <= 24'd0;
        end else if (stb) begin
            phase <= phase_next;
        end
    end

    //========================================================================
    // Quadrant mapping
    //========================================================================
    wire [1:0] quad    = phase[23:22];
    wire [7:0] idx_fwd = phase[21:14];
    wire [7:0] idx_rev = 8'd255 - phase[21:14];
    wire [7:0] tbl_idx = quad[0] ? idx_rev : idx_fwd;

    //========================================================================
    // Sine table lookup
    //========================================================================
    wire [15:0] tbl_val;
    assign tbl_val = SINE_TABLE[(255 - tbl_idx) * 16 +: 16];

    //========================================================================
    // Output: signed 16-bit = sign(quad[1]) * amplitude * tbl_val / 32768
    //========================================================================
    wire signed [31:0] prod;
    wire signed [15:0] sample_pre;

    assign prod       = $signed({{16{tbl_val[15]}}, tbl_val}) * $signed({{8{1'b0}}, amplitude});
    assign sample_pre = prod[23:8];

    wire signed [15:0] sample_raw;
    assign sample_raw = quad[1] ? (~sample_pre + 1'b1) : sample_pre;

    //========================================================================
    // Output register
    //========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            sample <= 16'd0;
        end else if (!enable) begin
            sample <= 16'd0;
        end else begin
            sample <= sample_raw;
        end
    end

endmodule
