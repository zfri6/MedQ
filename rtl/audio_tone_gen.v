//============================================================================
// audio_tone_gen - 48 kHz test/alert tone generator
//
// Clock domain : clk_pix (25.000 MHz)
// Timing      : stb = 48 kHz gate (from audio_sample_clk)
//
// Algorithm: 1/4-cycle sine lookup table (256 entries, Q15), phase accumulator.
//   phase[23:22] -> quadrant:
//     00 -> QI : +sin   (table[phase[21:14]])
//     01 -> QII: +sin   (table[255-phase[21:14]])
//     10 -> QIII: -sin  (table[phase[21:14]])
//     11 -> QIV : -sin  (table[255-phase[21:14]])
//
// Frequency: f = freq_inc * 48000 / 2^24  (freq_inc is 24-bit)
//   440 Hz (A4) -> freq_inc = 349525
//
// Reference: doc/arch/interface_contract.yaml (frozen)
//============================================================================
`timescale 1ns / 1ps

